export const LANGS = Object.keys(STRINGS);

export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.en;
  const t = (key, vars = {}) => {
    const s = table[key] ?? STRINGS.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  };
  // Picks skippedOne / skippedFew / skippedMany by the language's plural rules.
  t.plural = (base, n, vars = {}) => {
    const cat = new Intl.PluralRules(lang).select(n); // en: one/other; uk: one/few/many/other
    const key = cat === 'one' ? `${base}One` : cat === 'few' ? `${base}Few` : `${base}Many`;
    return t(table[key] ? key : `${base}Many`, { n, ...vars });
  };
  t.lang = lang;
  return t;
}

// "4–11 October 2026" / "4–11 жовтня 2026 р."
export function formatDates(start, end, lang) {
  try {
    const a = new Date(`${start}T12:00:00`), b = new Date(`${end || start}T12:00:00`);
    const f = new Intl.DateTimeFormat(lang === 'uk' ? 'uk-UA' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
    const s = f.formatRange ? f.formatRange(a, b) : `${f.format(a)} – ${f.format(b)}`;
    // Same-month ranges read as "4–11", whatever spacing the browser puts around the dash.
    return s.replace(/(\d)\s*[–—-]\s*(\d)/, '$1–$2');
  } catch { return ''; }
}

// Picks the right language from a {en, uk} object or plain string.
export function pick(value, lang) {
  if (value == null) return '';
  if (typeof value === 'string') return value;
  return value[lang] || value.en || Object.values(value)[0] || '';
}
